void sort() {
  int i, j;
  for (i = 0; i < 100 - 1; i++) {
    for (j = 0; j < 100 - i - 1; j++) {
      if (arr[j] > arr[j + 1]) {
        int temp = arr[j];
        arr[j] = arr[j + 1];
        arr[j + 1] = temp;
      }
    }
  }
}

// should not overflow as integers are small
long long sum_odd() {
  long long res = 0;
  for (int i = 0; i < 100; ++i) {
    if (i % 2)
      res += arr[i];
  }
  return res;
}

long long test() {
  sort();
  return sum_odd();
}
